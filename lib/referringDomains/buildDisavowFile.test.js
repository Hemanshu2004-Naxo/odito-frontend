import { describe, expect, test } from "vitest"
import { buildDisavowFile, disavowFileName, DISAVOW_WARNING } from "./buildDisavowFile"

const NOW = new Date("2026-10-28T23:59:00Z")

describe("buildDisavowFile — Google's format", () => {
  test("a comment first line, then one 'domain:' line per domain", () => {
    const { text, count } = buildDisavowFile(["spam-one.com", "spam-two.net"], { target: "asgeyehospital.com", now: NOW })
    expect(text).toBe("# Disavow file for asgeyehospital.com — generated by Odito on 2026-10-28\ndomain:spam-one.com\ndomain:spam-two.net\n")
    expect(count).toBe(2)
  })
  test("the order of the list is kept", () => {
    expect(buildDisavowFile(["b.com", "a.com", "c.com"], { now: NOW }).text.split("\n").slice(1, 4)).toEqual(["domain:b.com", "domain:a.com", "domain:c.com"])
  })
  test("every entry is cleaned with the shared normalizer, and repeats are removed", () => {
    const { text, count } = buildDisavowFile([" HTTPS://www.Spam.com/path ", "spam.com", "Other.org"], { now: NOW })
    expect(text).toContain("domain:spam.com\ndomain:other.org\n")
    expect(count).toBe(2)
  })
  test("an entry that is not a domain is dropped (a malformed line could make Google reject the whole file) and reported", () => {
    const out = buildDisavowFile(["ok.com", "not a domain", "localhost", "", null, 42], { now: NOW })
    expect(out.text).toBe("# Disavow file for your site — generated by Odito on 2026-10-28\ndomain:ok.com\n")
    expect(out.skipped).toEqual(["not a domain", "localhost", "", "null", "42"])
  })
  test("the date is the UTC day; the target in the comment is cleaned too", () => {
    expect(buildDisavowFile([], { target: "https://www.Example.com/x", now: new Date("2026-01-01T00:30:00Z") }).text).toBe("# Disavow file for example.com — generated by Odito on 2026-01-01\n")
  })
  test("an empty list is just the comment and a count of 0", () => {
    const out = buildDisavowFile([], { target: "a.com", now: NOW })
    expect(out.count).toBe(0)
    expect(out.text.split("\n").filter(Boolean)).toHaveLength(1)
    expect(buildDisavowFile(undefined, { now: NOW }).count).toBe(0)
  })
  test("no line is a URL, a path or a wildcard: only domain: entries and the comment", () => {
    const lines = buildDisavowFile(["a.com", "b.org"], { target: "x.com", now: NOW }).text.trim().split("\n")
    for (const l of lines.slice(1)) expect(l).toMatch(/^domain:[a-z0-9.-]+$/)
    expect(lines[0].startsWith("# ")).toBe(true)
  })
  test("a long list stays one line per domain", () => {
    const many = Array.from({ length: 5000 }, (_, i) => `site${i}.com`)
    expect(buildDisavowFile(many, { now: NOW }).text.trim().split("\n")).toHaveLength(5001)
  })
})

describe("file name and warning", () => {
  test("disavow_<domain>_<date>.txt", () => {
    expect(disavowFileName("https://www.asgeyehospital.com/", NOW)).toBe("disavow_asgeyehospital.com_2026-10-28.txt")
    expect(disavowFileName(null, NOW)).toBe("disavow_domain_2026-10-28.txt")
  })
  test("the warning shown before the download is the one in the brief", () => {
    expect(DISAVOW_WARNING).toBe("Only disavow domains you are sure are harmful. Upload this file in Google Search Console's Disavow Links tool.")
  })
})

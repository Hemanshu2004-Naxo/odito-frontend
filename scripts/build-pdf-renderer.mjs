// Bundles pdf/src/serverRender.jsx (React + the report pages) into one CommonJS
// file that the backend loads. Re-run after changing anything under pdf/src:
//   node scripts/build-pdf-renderer.mjs
import { build } from 'esbuild';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.resolve(root, '..', 'backend', 'src', 'modules', 'pdf', 'render', 'vendor', 'reportDocument.cjs');

await build({
  entryPoints: [path.join(root, 'pdf/src/serverRender.jsx')],
  outfile: out,
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node18',
  loader: { '.js': 'jsx' },
  alias: { '@': root },
  define: { 'process.env.NODE_ENV': '"production"' },
  banner: { js: '/* GENERATED by frontend/scripts/build-pdf-renderer.mjs - do not edit. */' },
  logLevel: 'info',
});
console.log('wrote', out);
